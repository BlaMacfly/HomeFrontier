//! Toutes les chaînes affichées par le launcher, en français, anglais et japonais. La langue de l'interface se
//! choisit dans l'en-tête (réglage `ui_language`). Le journal reste en français.

use serde::{Deserialize, Serialize};

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum Lang {
    #[default]
    Fr,
    En,
    Ja,
}

impl Lang {
    pub const ALL: [Lang; 3] = [Lang::Fr, Lang::En, Lang::Ja];

    /// Nom de la langue dans cette langue (sélecteur).
    pub fn native_name(self) -> &'static str {
        match self {
            Lang::Fr => "Français",
            Lang::En => "English",
            Lang::Ja => "日本語",
        }
    }
}

