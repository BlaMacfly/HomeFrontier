impl Texts {
    pub fn state(&self, s: &crate::orchestrator::State) -> String {
        use crate::orchestrator::State::*;
        match s {
            NotInstalled(m) => format!("{} ({})", self.st_not_installed, m.join(", ")),
            Stopped => self.st_stopped.into(),
            Initializing => self.st_initializing.into(),
            StartingDb => self.st_starting_db.into(),
            StartingServer => self.st_starting_server.into(),
            Connecting => self.st_connecting.into(),
            Ready => self.st_ready.into(),
            Playing => self.st_playing.into(),
            Stopping => self.st_stopping.into(),
            Error(e) => format!("{} : {e}", self.st_error),
        }
    }

    /// Libellé d'un élément du jeu (`paths::Layout::optional_components`).
    pub fn component(&self, id: &str) -> &'static str {
        match id {
            "quests" => self.comp_quests,
            "client" => self.comp_client,
            _ => self.comp_stub,
        }
    }
}

pub fn texts(lang: Lang) -> &'static Texts {
    match lang {
        Lang::Fr => &FR,
        Lang::En => &EN,
        Lang::Ja => &JA,
    }
}

